
# ==========================================
#        OPERADORES ARITMÉTICOS - PYTHON
# ==========================================

# +   -> Adição             (a + b)
# -   -> Subtração          (a - b)
# *   -> Multiplicação      (a * b)
# **  -> Exponenciação      (a ** b)
# /   -> Divisão            (a / b)
# %   -> Resto da divisão   (a % b)
# //  -> Divisão inteira    (a // b)

# ==========================================
# EXEMPLOS:
# ==========================================

# 10 + 5  = 15
# 10 - 5  = 5
# 10 * 5  = 50
# 10 ** 2 = 100
# 10 / 3  = 3.333...
# 10 % 3  = 1
# 10 // 3 = 3

