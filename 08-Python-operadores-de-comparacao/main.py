
# ============================================================
#          OPERADORES DE COMPARAÇÃO - PYTHON
#          COMPARISON OPERATORS - PYTHON
# ============================================================

# ==  -> Igual a / Equal to
# !=  -> Diferente de / Not equal to
# >   -> Maior que / Greater than
# <   -> Menor que / Less than
# >=  -> Maior ou igual a / Greater than or equal to
# <=  -> Menor ou igual a / Less than or equal to

# ============================================================
# EXEMPLOS / EXAMPLES
# ============================================================

# ==  (Equal to)
# 5 == 5  -> True

# !=  (Not equal to)
# 5 != 3  -> True

# >   (Greater than)
# 5 > 3   -> True

# <   (Less than)
# 5 < 3   -> False

# >=  (Greater than or equal to)
# 5 >= 5  -> True

# <=  (Less than or equal to)
# 3 <= 5  -> True

# ============================================================
# VALORES BOOLEANOS / BOOLEAN VALUES
# ============================================================

# True  -> Verdadeiro
# False -> Falso

# ============================================================
# EXEMPLO PRÁTICO / PRACTICAL EXAMPLE
# ============================================================

numero1 = 10
numero2 = 5

print(numero1 == numero2)  # False
print(numero1 != numero2)  # True
print(numero1 > numero2)   # True
print(numero1 < numero2)   # False
print(numero1 >= numero2)  # True
print(numero1 <= numero2)  # False

